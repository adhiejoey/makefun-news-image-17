#!/usr/bin/env python3
"""Build-time font extractor for the news-image entry.

Renders the printable ASCII glyphs of DejaVu Sans Bold (SIL OFL, shipped
with most Linux systems) at 20 px and 16 px with Pillow and writes them
as compact bitmaps into fontdata.py, which main.py (stdlib only) uses to
draw text into the entry PNG. This script runs on the author's machine
only; the grader never runs it. Regenerate with: python3 tools/make_font.py
"""
import os
import string
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
OUT = os.path.join(ROOT, "fontdata.py")
FONT_PATH = "/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf"
# (pixel size, bitmap height): ascent + descent for DejaVu Bold.
SIZES = [(20, 24), (16, 19)]


def extract(font, size, height):
    ascent, _descent = font.getmetrics()
    chars = string.printable[:95]  # space .. ~ (ASCII 32..126)
    out = {}
    for ch in chars:
        advance = int(round(font.getlength(ch))) or 1
        bbox = font.getbbox(ch)
        if bbox is None:
            out[ch] = (advance, 0, 0, [0] * height)
            continue
        left, _top, right, _bottom = bbox
        width = right - left
        from PIL import Image, ImageDraw
        img = Image.new("L", (width + 4, height), 0)
        draw = ImageDraw.Draw(img)
        # Anchor "ls": left edge + baseline, so every glyph shares the
        # same baseline at row `ascent` (commas and descenders stay low).
        draw.text((2, ascent), ch, font=font, fill=255, anchor="ls")
        rows = []
        for y in range(height):
            bits = 0
            for j in range(width):
                if img.getpixel((2 + left + j, y)) > 128:
                    bits |= 1 << (width - 1 - j)
            rows.append(bits)
        out[ch] = (advance, left, width, rows)
    return out


def main() -> None:
    try:
        from PIL import ImageFont
    except ImportError:
        print("Pillow is required to extract the font; pip install pillow", file=sys.stderr)
        raise SystemExit(1)
    lines = []
    lines.append("# Generated by tools/make_font.py from DejaVu Sans Bold")
    lines.append("# (SIL Open Font License 1.1). Bitmaps at 20 px and 16 px.")
    lines.append("# Each glyph: (advance_px, x_offset, ink_width, [row bitmask, ...]).")
    lines.append("# FONTS[size] = (bitmap_height, {char: glyph}).")
    lines.append("FONTS = {")
    for size, height in SIZES:
        font = ImageFont.truetype(FONT_PATH, size)
        glyphs = extract(font, size, height)
        lines.append("    %d: (%d, {" % (size, height))
        for ch, (adv, off, w, rows) in glyphs.items():
            lines.append("        %r: (%d, %d, %d, %s)," % (ch, adv, off, w, rows))
        lines.append("    }),")
    lines.append("}")
    # Backwards-compatible aliases for the 20 px face.
    lines.append("HEIGHT, GLYPHS = FONTS[20]")
    with open(OUT, "w", encoding="ascii") as fh:
        fh.write("\n".join(lines) + "\n")
    print("wrote %s (%d sizes x 95 glyphs)" % (OUT, len(SIZES)))


if __name__ == "__main__":
    main()
